from sh_notice_mcp.notable import find_notable_rules

# 실제 고덕강일 3단지 공고문 문장 (p.84, p.108-109, pdf 줄바꿈 그대로)
P84 = ("■ 공급신청 자격자\n•(청년 특별공급) 주택공급신청자는 무주택자만 가능합니다.\n"
       "※ 부부(예비신혼부부 제외)는 당첨자 발표일이 같은 주택에 대해 각각 청약할 수 있으나, 중복당첨된 경우 청약 접수일(분 단위까지의 접수시간을 포함)이 빠른\n"
       "사람의 당첨만을 인정하며 후 접수분은 무효 처리합니다.")
P108 = ("■ 특별공급(청년, 신혼부부, 생애최초, 신생아) 및 일반공급\n"
        "• 공급유형별로 자격요건을 충족하는 분은 특별공급 1개, 일반공급 1개 중복신청이 가능하나 특별공급 당첨자로 선정되면 일반공급 당첨자 선정에서\n"
        "제외됩니다. 단, 신청자 본인 외 다른 세대구성원이 일반공급 또는 특별공급에 청약하여 한 곳이라도 당첨될 경우 중복청약으로 모두 부적격 처리\n"
        "되오니 유의하시기 바랍니다.\n• 특별공급 간 중복청약할 수 없으며 청년·신혼부부·생애최초·신생아 특별공급 중 2개 이상의 자격에 해당할 경우에도 하나의 특별공급만 신청 가능합\n니다.")


def test_finds_strategy_rules_with_pages():
    pages = [""] * 83 + [P84] + [""] * 23 + [P108]
    r = {x["rule"]: x for x in find_notable_rules(pages)}
    assert r["특별공급+일반공급 동시 신청"]["page"] == 108
    assert r["특별공급+일반공급 동시 신청"]["quote"].startswith("공급유형별로 자격요건을 충족하는 분은 특별공급 1개")
    assert r["부부 각각 청약 가능"]["page"] == 84
    assert "각각 청약할 수 있으나" in r["부부 각각 청약 가능"]["quote"]
    assert r["특별공급끼리는 중복 불가"]["page"] == 108
    assert "부적격" in r["다른 세대원 청약 시 부적격"]["quote"]


def test_nothing_found_on_unrelated_text():
    assert find_notable_rules(["공급일정 2026. 9. 14.", ""]) == []
